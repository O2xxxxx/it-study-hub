import { chromium } from 'playwright-core'
const browser = await chromium.launch({ executablePath: 'C:/Program Files/Google/Chrome/Application/chrome.exe', headless: true })
const page = await (await browser.newContext({ viewport: { width: 1440, height: 960 } })).newPage()
const logs = []
page.on('console', (m) => logs.push(m.type() + ':' + m.text()))
page.on('response', async (r) => { if (r.url().includes('/api/')) logs.push('API ' + r.status() + ' ' + r.url().replace('http://127.0.0.1:5173','')) })
await page.goto('http://127.0.0.1:5173/register', { waitUntil: 'networkidle' })
await page.fill('#username', 'e2edbg02')
await page.fill('#nickname', '调试员')
await page.fill('#password', 'e2e12345')
await page.fill('#confirm', 'e2e12345')
await page.locator('button[type=submit]').first().click()
await page.waitForTimeout(3000)
console.log('URL', page.url())
const me = await page.evaluate(async () => { const r = await fetch('/api/auth/me', { credentials: 'include' }); return { status: r.status, text: (await r.text()).slice(0, 300) } })
console.log('ME', JSON.stringify(me))
console.log('HEADER', (await page.locator('header').innerText()).replace(/\n+/g, ' | ').slice(0, 200))
console.log('LOGS', JSON.stringify(logs.slice(-10)))
await browser.close()
